import { readFile, writeFile, readdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = fileURLToPath(new URL('../', import.meta.url));
const bundle = await build({
  absWorkingDir: root,
  entryPoints: ['widget-renderer/MarkdownRenderer.mjs'],
  bundle: true,
  format: 'iife',
  globalName: 'WidgetMarkdown',
  platform: 'neutral',
  mainFields: ['module', 'main'],
  target: ['es2020'],
  minify: true,
  legalComments: 'inline',
  banner: { js: '/* Generated by npm run build:widgets. Licenses: widget-markdown.LICENSE.txt */' },
  write: false,
  metafile: true,
});

const packages = new Set();

for (const input of Object.keys(bundle.metafile.inputs)) {
  const match = input.match(/^node_modules\/((?:@[^/]+\/)?[^/]+)/);

  if (match) {
    packages.add(match[1]);
  }
}

const licenses = [];

for (const name of [...packages].sort()) {
  const directory = path.join(root, 'node_modules', name);
  const files = await readdir(directory);
  const license = files.find((file) => {
    return /^(license|licence)(\.(md|txt))?$/i.test(file);
  });

  if (!license) {
    throw new Error(`Missing bundled dependency license: ${name}`);
  }

  const text = await readFile(path.join(directory, license), 'utf8');
  licenses.push(`${name}\n\n${text}`);
}

// Read each authored asset once so every widget receives the same source snapshot.
const assets = [
  ['widget-markdown.js', bundle.outputFiles[0].contents],
  ['widget-markdown.LICENSE.txt', licenses.join('\n\n---\n\n')],
];
const sourceAssets = [
  ['widget-result.js', 'lib/WidgetResult.js'],
  ['widget-controller.js', 'lib/WidgetInteractionController.js'],
  ['widget-host.js', 'widget-renderer/WidgetHost.js'],
  ['result-renderer.js', 'widget-renderer/ResultRenderer.js'],
  ['result-renderer.css', 'widget-renderer/ResultRenderer.css'],
];
const sourceContents = await Promise.all(
  sourceAssets.map(async ([asset, source]) => {
    const content = await readFile(path.join(root, source));

    return [asset, content];
  }),
);
assets.push(...sourceContents);

for (const widget of [
  'script-result',
  'script-result-transparent',
  'script-button',
  'script-button-transparent',
]) {
  const directory = path.join(root, 'widgets', widget, 'public');

  for (const [asset, content] of assets) {
    await writeFile(path.join(directory, asset), content);
  }
}

console.log(
  `Built Markdown renderer (${bundle.outputFiles[0].contents.length} bytes) and synchronized four widgets.`,
);
